let currentLang = localStorage.getItem('skysoft_lang') || 'en';

/**
 * Get translation for a key.
 */
function t(key) {
    const lang = I18N[currentLang] || I18N.en;
    return lang[key] || I18N.en[key] || key;
}

/**
 * Get weather condition translation.
 */
function tWeather(condition) {
    return t(condition) || t('unknown');
}

/**
 * Set current language and update UI.
 */
function setLanguage(lang) {
    if (!I18N[lang]) {
        lang = 'en';
    }
    currentLang = lang;
    localStorage.setItem('skysoft_lang', lang);
    document.documentElement.lang = lang;
    applyTranslations();
}

/**
 * Apply translations to all elements with data-i18n attributes.
 */
function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = t(key);
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        el.title = t(key);
    });
}

/**
 * Initialize language selector.
 */
function initLanguage() {
    const select = document.getElementById('lang-select');
    if (select) {
        select.value = currentLang;
        select.addEventListener('change', () => {
            setLanguage(select.value);
            if (typeof onLanguageChange === 'function') {
                onLanguageChange();
            }
        });
    }
    applyTranslations();
}

document.addEventListener('DOMContentLoaded', initLanguage);
